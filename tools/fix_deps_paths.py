"""Repair the two dependency-resolution bugs, keeping every other key intact.

WHAT IS BROKEN, MEASURED
------------------------
1. `activate_deps.bat` and `.env.local` are auto-generated by
   `tools/configure_deps.py write`, and both point `ISRNACIRC_ROOT` at
   `C:\\Users\\<user>\\deploy\\...\\IsRNAcirc_standalone`. That directory no longer exists,
   and it is a non-ASCII path, which is the second problem: `isrnacirc_wrapper.py`
   records that `CG_to_allatom.exe` is a GBK-encoded native binary and cannot be run
   through a non-ASCII path. The working copy lives at `<repo>/_isrnacirc_ascii`,
   which `discover` finds but `write` was never re-run to record.

2. With the variables unset, `isrnacirc_wrapper` resolves to empty strings:

       ISRNACIRC_BIN_DIR unset -> _CG_TO_AA_EXE = "" -> cg_to_allatom() raises
       FileNotFoundError

   So in a stock shell the CG->all-atom step cannot run at all. The variables are
   real inputs, not hints: `configure_deps` finds the tool by scanning for it
   (`"probe": None` for isrnacirc), but the pipeline reads the variables.

3. `RNABPFLOW_ROOT` points at `C:\\Torusfold-physics\\RNAbpFlow`, which does not
   exist. The real checkout is `C:\\baidunetdiskdownload\\TorusFold-tools\\RNAbpFlow`,
   where the 193.6 MB checkpoint is present and `inference_rocm.py` is not. Fixing the
   path does NOT make RNAbpFlow work -- it makes the report say the true thing, that
   the ROCm inference script is the missing piece, instead of blaming a wrong path.
   Claiming otherwise would be the worse bug.

WHAT THIS DOES NOT DO
---------------------
It does not touch `TF_FEEDBACK_MAIL_*` or any other key it has no business in. The
existing file is read, only the named keys are replaced, and the result is written
through the module's own `write_env_local` / `write_activate_bat` so the format stays
the one the tool produces. A timestamped backup is taken first.

Usage:
    python tools/fix_deps_paths.py --dry-run
    python tools/fix_deps_paths.py --apply
    python tools/fix_deps_paths.py --apply --isrnacirc D:\\tools\\isRNAcirc_ascii \\
                                          --rnabpflow D:\\tools\\RNAbpFlow
"""
from __future__ import annotations

import argparse
import datetime
import importlib.util
import pathlib
import shutil
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent

# The ASCII copy of the toolset this repository promotes to: exe + 4 DLLs + Data/.
# Both locations are derived from where this repository sits rather than written out
# as absolute paths, so the script stays usable on another machine; `--isrnacirc`
# and `--rnabpflow` override them when a checkout lives somewhere else.
ISRNACIRC_ASCII = REPO / "_isrnacirc_ascii"

# The real RNAbpFlow checkout. Its checkpoint is what the installer fetches; the
# ROCm inference script is a separate, team-held artefact.
RNABPFLOW_REAL = REPO.parent / "TorusFold-tools" / "RNAbpFlow"


def load_configure_deps():
    spec = importlib.util.spec_from_file_location(
        "configure_deps", REPO / "tools" / "configure_deps.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    global ISRNACIRC_ASCII, RNABPFLOW_REAL

    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--apply", action="store_true")
    g.add_argument("--dry-run", action="store_true")
    ap.add_argument("--isrnacirc", default=None,
                    help="the ASCII-only copy of the isRNAcirc toolset "
                         "(default: <repo>/_isrnacirc_ascii)")
    ap.add_argument("--rnabpflow", default=None,
                    help="the RNAbpFlow checkout "
                         "(default: <repo>/../TorusFold-tools/RNAbpFlow)")
    args = ap.parse_args()

    if args.isrnacirc:
        ISRNACIRC_ASCII = pathlib.Path(args.isrnacirc).resolve()
    if args.rnabpflow:
        RNABPFLOW_REAL = pathlib.Path(args.rnabpflow).resolve()

    cd = load_configure_deps()
    env_local = REPO / ".env.local"
    bat = REPO / "activate_deps.bat"

    # -- preconditions ------------------------------------------------------
    problems = []
    if not (ISRNACIRC_ASCII / "bin" / "CG_to_allatom.exe").is_file():
        problems.append(f"{ISRNACIRC_ASCII / 'bin' / 'CG_to_allatom.exe'} missing")
    coeff = ISRNACIRC_ASCII / "Data" / "data" / "IsRNA2"
    for name in ("AA_baseA.dat", "AA_baseG.dat", "AA_baseC.dat",
                 "AA_baseU.dat", "AA_backbone.dat"):
        if not (coeff / name).is_file():
            problems.append(f"{coeff / name} missing")
    if str(ISRNACIRC_ASCII).encode("ascii", "ignore").decode() != str(ISRNACIRC_ASCII):
        problems.append(f"{ISRNACIRC_ASCII} is not ASCII-only, which defeats the point")
    if not RNABPFLOW_REAL.is_dir():
        problems.append(f"{RNABPFLOW_REAL} missing")
    if problems:
        print("ABORT -- preconditions not met:")
        for p in problems:
            print(f"  {p}")
        return 2
    print("preconditions OK: the ASCII toolset is complete and the RNAbpFlow checkout exists")
    print()

    # -- the target values --------------------------------------------------
    target = {
        "ISRNACIRC_BIN_DIR": str(ISRNACIRC_ASCII / "bin"),
        "ISRNACIRC_ROOT": str(ISRNACIRC_ASCII),
        "CG_TO_ALLATOM_COEFF": str(coeff),
        "RNABPFLOW_ROOT": str(RNABPFLOW_REAL),
        "RNABPFLOW_PYTHON": sys.executable,
    }

    before = cd.read_env_local(str(env_local)) if env_local.is_file() else {}
    print(f"{'key':<24} {'before':<58} after")
    for k, v in target.items():
        old = before.get(k, "(unset)")
        mark = "same" if old == v else "CHANGE"
        print(f"  {k:<22} {old[:56]:<58} {v}")
        print(f"  {'':<22} -> {mark}")
    print()

    kept = sorted(k for k in before if k not in target)
    print(f"keys preserved untouched ({len(kept)}):")
    for k in kept:
        print(f"  {k}")

    if args.dry_run:
        print()
        print("[dry run] nothing written. Pass --apply.")
        return 0

    # -- backup -------------------------------------------------------------
    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = REPO.parent / f"_deps_backup_{stamp}"
    backup.mkdir(parents=True, exist_ok=True)
    for f in (env_local, bat):
        if f.is_file():
            shutil.copy2(f, backup / f.name)
    print(f"\nbackup: {backup}")

    # -- merge and write through the tool's own writers ---------------------
    merged, added, kept_names = cd.merge_env(str(env_local), target)
    cd.write_env_local(merged, str(env_local))
    cd.write_activate_bat(merged, str(bat))
    print(f"wrote {env_local.name} and {bat.name}")
    print(f"  added: {added}")
    print(f"  kept : {len(kept_names)} existing keys")

    # -- verify -------------------------------------------------------------
    after = cd.read_env_local(str(env_local))
    print()
    print("verification")
    ok = True
    for k, v in target.items():
        good = after.get(k) == v
        ok &= good
        print(f"  {'OK ' if good else 'BAD'} {k} = {after.get(k)}")
    for k in ("TF_FEEDBACK_MAIL_USER", "TF_FEEDBACK_MAIL_TO", "TF_FEEDBACK_MAIL_HOST"):
        if k in before:
            good = after.get(k) == before[k]
            ok &= good
            print(f"  {'OK ' if good else 'BAD'} {k} preserved = {after.get(k)}")
    print()
    print("RESULT:", "PASS" if ok else "FAIL -- restore from " + str(backup))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
